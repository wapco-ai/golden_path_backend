-- Explicit stairs between two access points on the same floor.
BEGIN;

CREATE TABLE public.same_floor_stairs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stair_area_id bigint NOT NULL UNIQUE REFERENCES public.areas(id) ON DELETE CASCADE,
    floor smallint NOT NULL REFERENCES public.routing_floors(floor),
    start_access_id bigint REFERENCES public.door_access_points(id) ON DELETE SET NULL,
    end_access_id bigint REFERENCES public.door_access_points(id) ON DELETE SET NULL,
    start_area_id bigint NOT NULL REFERENCES public.areas(id) ON DELETE CASCADE,
    end_area_id bigint NOT NULL REFERENCES public.areas(id) ON DELETE CASCADE,
    direction text NOT NULL DEFAULT 'both' CHECK (direction IN ('both', 'forward', 'reverse')),
    is_active boolean NOT NULL DEFAULT true,
    travel_seconds numeric CHECK (travel_seconds > 0 AND travel_seconds <= 3600),
    reverse_seconds numeric CHECK (reverse_seconds > 0 AND reverse_seconds <= 3600),
    info jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(info) = 'object'),
    version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (start_access_id <> end_access_id),
    CHECK (stair_area_id NOT IN (start_area_id, end_area_id))
);

CREATE INDEX same_floor_stairs_start_access_idx ON public.same_floor_stairs(start_access_id);
CREATE INDEX same_floor_stairs_end_access_idx ON public.same_floor_stairs(end_access_id);
CREATE UNIQUE INDEX routing_edges_static_same_floor_stair_key
    ON public.routing_edges_static ((attrs->>'stair_id')) WHERE attrs->>'edge_type' = 'same_floor_stair';
CREATE INDEX routing_edges_static_same_floor_stair_id_idx
    ON public.routing_edges_static (id) WHERE attrs->>'edge_type' = 'same_floor_stair';

-- Existing app/reader roles retain equivalent access to the new link definitions.
DO $grant$
DECLARE
    acl record;
BEGIN
    FOR acl IN
        SELECT DISTINCT r.rolname, a.privilege_type
        FROM pg_class c
        CROSS JOIN LATERAL aclexplode(c.relacl) a
        JOIN pg_roles r ON r.oid = a.grantee
        WHERE (
            c.oid = 'public.routing_connectors'::regclass
            AND a.privilege_type IN ('SELECT', 'INSERT', 'UPDATE', 'DELETE')
        ) OR (
            c.oid = 'public.routing_edges_static'::regclass AND a.privilege_type = 'SELECT'
        )
    LOOP
        EXECUTE format('GRANT %s ON public.same_floor_stairs TO %I', acl.privilege_type, acl.rolname);
        IF acl.privilege_type = 'INSERT' THEN
            EXECUTE format('GRANT USAGE ON SEQUENCE public.same_floor_stairs_id_seq TO %I', acl.rolname);
        END IF;
    END LOOP;
END;
$grant$;

-- Resolve the precise landing-side nodes. The footprint and landing polygons only validate the line.
CREATE FUNCTION public.fn_same_floor_stair_candidate(
    p_stair_area_id bigint, p_floor smallint, p_start_access_id bigint, p_end_access_id bigint,
    p_start_area_id bigint, p_end_area_id bigint
)
RETURNS TABLE(start_node_id bigint, end_node_id bigint, geom public.geometry)
LANGUAGE sql STABLE STRICT
SET search_path = pg_catalog, public
AS $fn$
    SELECT ns.id, ne.id, line.geom
    FROM public.areas body
    JOIN public.areas la ON la.id = p_start_area_id AND la.floor = p_floor
    JOIN public.areas lb ON lb.id = p_end_area_id AND lb.floor = p_floor
    JOIN public.door_access_points ds ON ds.id = p_start_access_id AND ds.floor = p_floor
    JOIN public.door_access_points de ON de.id = p_end_access_id AND de.floor = p_floor
    JOIN public.routing_nodes ns ON ns.ref_table = 'door_access_points' AND ns.ref_id = ds.id
        AND ns.floor = p_floor AND ns.area_id = la.id
    JOIN public.routing_nodes ne ON ne.ref_table = 'door_access_points' AND ne.ref_id = de.id
        AND ne.floor = p_floor AND ne.area_id = lb.id
    CROSS JOIN LATERAL (SELECT ST_MakeLine(ns.geom, ne.geom) AS geom) line
    WHERE body.id = p_stair_area_id AND body.floor = p_floor
      AND body.area_type::text = 'stair_area'
      AND public.fn_area_routing_role(body.area_type, body.attrs) = 'transparent'
      AND public.fn_area_routing_role(la.area_type, la.attrs) = 'routable'
      AND public.fn_area_routing_role(lb.area_type, lb.attrs) = 'routable'
      AND ds.id <> de.id AND ns.id <> ne.id
      AND NOT COALESCE(ds.needs_review, false) AND NOT COALESCE(de.needs_review, false)
      AND la.id IN (ds.from_area, ds.to_area) AND lb.id IN (de.from_area, de.to_area)
      AND ST_Equals(ns.geom, ds.geom) AND ST_Equals(ne.geom, de.geom)
      AND CASE WHEN ST_IsValid(body.geom) AND ST_IsValid(la.geom) AND ST_IsValid(lb.geom) THEN
          ST_Covers(la.geom, ns.geom) AND ST_Covers(lb.geom, ne.geom)
          AND ST_DWithin(body.geom, ns.geom, 0.30) AND ST_DWithin(body.geom, ne.geom, 0.30)
          AND ST_Length(line.geom) > 0.01
          AND ST_Relate(line.geom, body.geom, 'T********')
          AND ST_Covers(ST_UnaryUnion(ST_Collect(ARRAY[body.geom, la.geom, lb.geom])), line.geom)
          AND NOT EXISTS (
              SELECT 1 FROM public.areas a
              WHERE a.floor = p_floor AND a.id <> body.id AND a.geom && body.geom
                AND public.fn_area_routing_role(a.area_type, a.attrs) = 'routable'
                AND ST_Relate(ST_MakeValid(a.geom), body.geom, '2********')
          )
      ELSE false END
    ORDER BY ns.id, ne.id
    LIMIT 1;
$fn$;

CREATE FUNCTION public.fn_same_floor_stair_edge_geom(p_stair_id bigint)
RETURNS public.geometry
LANGUAGE sql STABLE STRICT
SET search_path = pg_catalog, public
AS $fn$
    SELECT c.geom FROM public.same_floor_stairs s
    CROSS JOIN LATERAL public.fn_same_floor_stair_candidate(
        s.stair_area_id, s.floor, s.start_access_id, s.end_access_id, s.start_area_id, s.end_area_id
    ) c
    WHERE s.id = p_stair_id;
$fn$;

CREATE FUNCTION public.fn_refresh_same_floor_stair(p_stair_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $fn$
DECLARE
    stair_floor smallint;
    stair_area bigint;
    lower_node bigint;
    upper_node bigint;
    line public.geometry;
BEGIN
    SELECT s.floor, s.stair_area_id, c.start_node_id, c.end_node_id, c.geom
    INTO stair_floor, stair_area, lower_node, upper_node, line
    FROM public.same_floor_stairs s
    CROSS JOIN LATERAL public.fn_same_floor_stair_candidate(
        s.stair_area_id, s.floor, s.start_access_id, s.end_access_id, s.start_area_id, s.end_area_id
    ) c
    WHERE s.id = p_stair_id AND s.is_active;

    IF line IS NULL THEN
        DELETE FROM public.routing_edges_static e
        WHERE e.attrs->>'edge_type' = 'same_floor_stair' AND e.attrs->>'stair_id' = p_stair_id::text;
        RETURN false;
    END IF;

    INSERT INTO public.routing_edges_static(floor, src, dst, geom, base_cost, attrs)
    VALUES (stair_floor, lower_node, upper_node, line, ST_Length(line),
        jsonb_build_object('edge_type', 'same_floor_stair', 'stair_id', p_stair_id,
            'stair_area_id', stair_area, 'valid_inside_area', true))
    ON CONFLICT ((attrs->>'stair_id')) WHERE attrs->>'edge_type' = 'same_floor_stair'
    DO UPDATE SET floor = EXCLUDED.floor, src = EXCLUDED.src, dst = EXCLUDED.dst,
        geom = EXCLUDED.geom, base_cost = EXCLUDED.base_cost, attrs = EXCLUDED.attrs
    WHERE (routing_edges_static.floor, routing_edges_static.src, routing_edges_static.dst,
        routing_edges_static.geom, routing_edges_static.base_cost, routing_edges_static.attrs)
        IS DISTINCT FROM (EXCLUDED.floor, EXCLUDED.src, EXCLUDED.dst,
            EXCLUDED.geom, EXCLUDED.base_cost, EXCLUDED.attrs);
    RETURN true;
END;
$fn$;

-- Definitions and their graph rows are kept in sync in the transaction that changes them.
CREATE FUNCTION public.fn_same_floor_stair_definition_changed()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM public.fn_refresh_same_floor_stair(OLD.id);
    ELSE
        PERFORM public.fn_refresh_same_floor_stair(NEW.id);
    END IF;
    RETURN NULL;
END;
$fn$;

CREATE TRIGGER same_floor_stair_definition_changed
    AFTER INSERT OR UPDATE OR DELETE ON public.same_floor_stairs
    FOR EACH ROW EXECUTE FUNCTION public.fn_same_floor_stair_definition_changed();

CREATE FUNCTION public.fn_same_floor_stair_landing_removed()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $fn$
BEGIN
    NEW.is_active := false;
    NEW.version := OLD.version + 1;
    NEW.updated_at := now();
    RETURN NEW;
END;
$fn$;

CREATE TRIGGER same_floor_stair_landing_removed
    BEFORE UPDATE OF start_access_id, end_access_id ON public.same_floor_stairs
    FOR EACH ROW WHEN (
        (OLD.start_access_id IS NOT NULL AND NEW.start_access_id IS NULL)
        OR (OLD.end_access_id IS NOT NULL AND NEW.end_access_id IS NULL)
    )
    EXECUTE FUNCTION public.fn_same_floor_stair_landing_removed();

CREATE FUNCTION public.fn_same_floor_stair_access_changed()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
    old_access bigint;
    new_access bigint;
    stair_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'door_access_points' THEN
        old_access := OLD.id;
        new_access := NEW.id;
    ELSE
        IF TG_OP = 'UPDATE' AND OLD.ref_table = 'door_access_points' THEN
            old_access := OLD.ref_id;
        END IF;
        IF NEW.ref_table = 'door_access_points' THEN
            new_access := NEW.ref_id;
        END IF;
    END IF;
    FOR stair_id IN
        SELECT s.id FROM public.same_floor_stairs s
        WHERE s.start_access_id IN (old_access, new_access) OR s.end_access_id IN (old_access, new_access)
        ORDER BY s.id
    LOOP
        PERFORM public.fn_refresh_same_floor_stair(stair_id);
    END LOOP;
    RETURN NULL;
END;
$fn$;

CREATE TRIGGER same_floor_stair_access_changed
    AFTER UPDATE OF geom, floor, from_area, to_area, needs_review ON public.door_access_points
    FOR EACH ROW EXECUTE FUNCTION public.fn_same_floor_stair_access_changed();

CREATE TRIGGER same_floor_stair_node_changed
    AFTER INSERT OR UPDATE OF geom, floor, area_id, ref_table, ref_id ON public.routing_nodes
    FOR EACH ROW EXECUTE FUNCTION public.fn_same_floor_stair_access_changed();

CREATE FUNCTION public.fn_same_floor_stair_area_changed()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
    old_area public.areas%ROWTYPE;
    new_area public.areas%ROWTYPE;
    stair_id bigint;
BEGIN
    IF TG_OP <> 'INSERT' THEN old_area := OLD; END IF;
    IF TG_OP <> 'DELETE' THEN new_area := NEW; END IF;

    IF TG_OP = 'UPDATE' AND (old_area.floor, old_area.area_type, old_area.geom,
        public.fn_area_routing_role(old_area.area_type, old_area.attrs))
        IS NOT DISTINCT FROM (new_area.floor, new_area.area_type, new_area.geom,
            public.fn_area_routing_role(new_area.area_type, new_area.attrs)) THEN
        RETURN NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.same_floor_stairs s
        WHERE s.is_active AND s.stair_area_id = new_area.id
          AND (new_area.area_type::text <> 'stair_area'
              OR public.fn_area_routing_role(new_area.area_type, new_area.attrs) <> 'transparent')
    ) OR EXISTS (
        SELECT 1 FROM public.same_floor_stairs s
        JOIN public.areas body ON body.id = s.stair_area_id
        JOIN public.areas a ON a.floor = body.floor AND a.id <> body.id AND a.geom && body.geom
        WHERE s.is_active AND new_area.id IN (a.id, body.id)
          AND public.fn_area_routing_role(a.area_type, a.attrs) = 'routable'
          AND ST_Relate(ST_MakeValid(a.geom), ST_MakeValid(body.geom), '2********')
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514',
            MESSAGE = 'An active stair footprint must be transparent and disjoint from routable areas; deactivate the stair before editing its map geometry',
            CONSTRAINT = 'same_floor_stairs_no_routable_overlap';
    END IF;

    FOR stair_id IN
        SELECT s.id FROM public.same_floor_stairs s
        JOIN public.areas body ON body.id = s.stair_area_id
        WHERE old_area.id IN (s.stair_area_id, s.start_area_id, s.end_area_id)
           OR new_area.id IN (s.stair_area_id, s.start_area_id, s.end_area_id)
           OR (s.floor = old_area.floor AND body.geom && old_area.geom)
           OR (s.floor = new_area.floor AND body.geom && new_area.geom)
        ORDER BY s.id
    LOOP
        PERFORM public.fn_refresh_same_floor_stair(stair_id);
    END LOOP;
    RETURN NULL;
END;
$fn$;

CREATE TRIGGER same_floor_stair_area_changed
    AFTER INSERT OR UPDATE OF geom, floor, area_type, attrs OR DELETE ON public.areas
    FOR EACH ROW EXECUTE FUNCTION public.fn_same_floor_stair_area_changed();

-- An area/door rebuild deletes incident edges before replacing their graph nodes.
-- Refresh only after the replacement, so the old node cannot be reattached before it is deleted.
CREATE FUNCTION public.fn_same_floor_stair_edge_removed()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
BEGIN
    PERFORM public.fn_refresh_same_floor_stair((OLD.attrs->>'stair_id')::bigint);
    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER same_floor_stair_edge_removed
    AFTER DELETE ON public.routing_edges_static DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW WHEN (OLD.attrs->>'edge_type' = 'same_floor_stair')
    EXECUTE FUNCTION public.fn_same_floor_stair_edge_removed();

REVOKE EXECUTE ON FUNCTION public.fn_refresh_same_floor_stair(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_same_floor_stair_definition_changed() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_same_floor_stair_access_changed() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_same_floor_stair_area_changed() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_same_floor_stair_edge_removed() FROM PUBLIC;

CREATE FUNCTION public.fn_same_floor_stair_access(
    p_stair_id bigint, p_now timestamptz, p_gender public.gender_enum, p_mode text
)
RETURNS TABLE(direction text, forward_cost numeric, reverse_cost numeric, penalty numeric)
LANGUAGE sql STABLE STRICT
SET search_path = pg_catalog, public
AS $fn$
    SELECT s.direction, s.travel_seconds * 1.2,
        COALESCE(s.reverse_seconds, s.travel_seconds) * 1.2,
        GREATEST(COALESCE(access.penalty_w, 1), 1)
    FROM public.same_floor_stairs s
    JOIN public.areas a ON a.id = s.stair_area_id AND a.floor = s.floor
    CROSS JOIN LATERAL public.fn_entity_access(
        'areas', a.id, p_now, p_gender, p_mode, s.floor, ST_PointOnSurface(a.geom)
    ) access
    WHERE s.id = p_stair_id AND s.is_active AND p_mode = 'walk'
      AND s.start_access_id IS NOT NULL AND s.end_access_id IS NOT NULL
      AND NOT a.is_closed AND access.allowed
      AND (a.attrs#>>'{access_policy,public_access}') IS DISTINCT FROM 'false'
      AND (a.allowed_gender = 'both' OR a.allowed_gender = p_gender)
      AND (
          s.info#>'{operational,gender_access}' IS NULL
          OR (s.info#>'{operational,gender_access}') ? 'both'
          OR (s.info#>'{operational,gender_access}') ? p_gender::text
          OR (p_gender = 'both' AND (s.info#>'{operational,gender_access}') ? 'family')
      )
      AND (a.attrs#>'{operational,transport_modes}' IS NULL
          OR (a.attrs#>'{operational,transport_modes}') ? 'walk')
      AND NOT EXISTS (
          SELECT 1 FROM public.fn_blocked_areas_from_admin(p_now, p_gender, p_mode, s.floor) b
          WHERE b.area_id = a.id AND b.restrict_type = 'close'
      )
      AND EXISTS (
          SELECT 1 FROM public.routing_edges_static e
          JOIN public.routing_nodes ns ON ns.id = e.src AND ns.floor = s.floor
              AND ns.ref_table = 'door_access_points' AND ns.ref_id = s.start_access_id AND ns.area_id = s.start_area_id
          JOIN public.routing_nodes ne ON ne.id = e.dst AND ne.floor = s.floor
              AND ne.ref_table = 'door_access_points' AND ne.ref_id = s.end_access_id AND ne.area_id = s.end_area_id
          JOIN public.door_access_points ds ON ds.id = s.start_access_id AND ds.floor = s.floor
              AND NOT COALESCE(ds.needs_review, false) AND ns.area_id IN (ds.from_area, ds.to_area)
          JOIN public.door_access_points de ON de.id = s.end_access_id AND de.floor = s.floor
              AND NOT COALESCE(de.needs_review, false) AND ne.area_id IN (de.from_area, de.to_area)
          WHERE e.attrs->>'edge_type' = 'same_floor_stair' AND e.attrs->>'stair_id' = s.id::text
            AND e.floor = s.floor AND e.attrs->>'stair_area_id' = s.stair_area_id::text
            AND ST_Equals(ns.geom, ds.geom) AND ST_Equals(ne.geom, de.geom)
            AND ST_OrderingEquals(e.geom, ST_MakeLine(ns.geom, ne.geom))
      );
$fn$;

CREATE FUNCTION public.fn_same_floor_stair_landing_areas(p_floor smallint)
RETURNS SETOF bigint
LANGUAGE sql STABLE STRICT SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT DISTINCT landing.id
    FROM public.same_floor_stairs s
    JOIN public.routing_edges_static e ON e.attrs->>'edge_type' = 'same_floor_stair'
        AND e.attrs->>'stair_id' = s.id::text AND e.floor = s.floor
    CROSS JOIN LATERAL (VALUES (s.start_area_id), (s.end_area_id)) landing(id)
    WHERE s.floor = p_floor AND s.is_active;
$fn$;

-- Keep the installed routing definitions and ACLs, changing only the feature's
-- hooks. Reverse the exact edits on rollback, without replacing newer SQL.
CREATE FUNCTION public.fn_patch_same_floor_stair_route_sql(p_install boolean)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $fn$
DECLARE
    patch record;
    edit_index integer;
    source_sql text;
    before_text text;
    after_text text;
    view_sql text;
BEGIN
    FOR patch IN
        WITH route_functions(signature) AS (VALUES
            ('public.fn_route_multifloor_edges(timestamptz,public.gender_enum,text,smallint,smallint,public.geometry,public.geometry,integer)'),
            ('public.fn_route_nearby_edges(timestamptz,public.gender_enum,text,smallint,smallint,public.geometry,public.geometry)'),
            ('public.fn_route_nearby_origin_edges(timestamptz,public.gender_enum,text,smallint,smallint,public.geometry,public.geometry)')
        )
        SELECT signature, array_agg(old_sql) AS old_sql, array_agg(new_sql) AS new_sql
        FROM (
        SELECT signature,
            'ST_Length(e.geom)/speed,ST_Length(e.geom)/speed,ST_Length(e.geom)' AS old_sql,
            'COALESCE(sfs.travel_seconds,ST_Length(e.geom)/speed),'
            || 'COALESCE(sfs.reverse_seconds,sfs.travel_seconds,ST_Length(e.geom)/speed),ST_Length(e.geom)' AS new_sql
        FROM route_functions
        UNION ALL
        SELECT signature,
            'FROM routing_floors f CROSS JOIN LATERAL fn_routing_edges_live_param(p_now,p_gender,p_mode,f.floor) e',
            'FROM routing_floors f CROSS JOIN LATERAL fn_routing_edges_live_param(p_now,p_gender,p_mode,f.floor) e'
            || E'\n  LEFT JOIN public.routing_edges_static sfs_edge ON sfs_edge.id=e.id AND sfs_edge.attrs->>''edge_type''=''same_floor_stair'''
            || E'\n  LEFT JOIN public.same_floor_stairs sfs ON sfs.id=(sfs_edge.attrs->>''stair_id'')::bigint'
        FROM route_functions
        UNION ALL
        SELECT 'public.fn_route_nearby_edges(timestamptz,public.gender_enum,text,smallint,smallint,public.geometry,public.geometry)',
            'AND e.ref_edge IS NOT NULL AND ST_GeometryType(e.geom)=''ST_LineString''',
            'AND e.ref_edge IS NOT NULL AND ST_GeometryType(e.geom)=''ST_LineString'''
            || E'\n      AND NOT EXISTS (SELECT 1 FROM public.routing_edges_static se WHERE se.id=e.ref_edge AND se.attrs->>''edge_type''=''same_floor_stair'')'
        UNION ALL
        SELECT 'public.fn_route_nearby_origin_edges(timestamptz,public.gender_enum,text,smallint,smallint,public.geometry,public.geometry)',
            'AND ST_DWithin(e.geom,v.search_geom,radius_m)',
            'AND ST_DWithin(e.geom,v.search_geom,radius_m)'
            || E'\n    AND NOT EXISTS (SELECT 1 FROM public.routing_edges_static se WHERE se.id=e.ref_edge AND se.attrs->>''edge_type''=''same_floor_stair'')'
        UNION ALL
        SELECT 'public.fn_routing_edges_live_param(timestamptz,public.gender_enum,text,smallint)',
            'e.live_cost AS cost,',
            'CASE'
            || E'\n        WHEN sfs.direction = ''reverse'' THEN (-1)::numeric'
            || E'\n        WHEN sfs.direction IS NOT NULL THEN'
            || E'\n            COALESCE(sfs.forward_cost * e.live_cost / NULLIF(e.base_cost, 0), e.live_cost) * sfs.penalty'
            || E'\n        ELSE e.live_cost'
            || E'\n    END AS cost,'
        UNION ALL
        SELECT 'public.fn_routing_edges_live_param(timestamptz,public.gender_enum,text,smallint)',
            'WHEN e.door_id IS NULL',
            'WHEN sfs.direction = ''forward'' THEN (-1)::numeric'
            || E'\n        WHEN sfs.direction IS NOT NULL THEN'
            || E'\n            COALESCE(sfs.reverse_cost * e.live_cost / NULLIF(e.base_cost, 0), e.live_cost) * sfs.penalty'
            || E'\n        WHEN e.door_id IS NULL'
        UNION ALL
        SELECT 'public.fn_routing_edges_live_param(timestamptz,public.gender_enum,text,smallint)',
            E'       ON dst_da.door_id = e.dst_door_ref_id\n\nWHERE',
            E'       ON dst_da.door_id = e.dst_door_ref_id\n'
            || E'LEFT JOIN LATERAL public.fn_same_floor_stair_access(\n'
            || E'    CASE WHEN e.attrs->>''edge_type'' = ''same_floor_stair'' THEN (e.attrs->>''stair_id'')::bigint END,\n'
            || E'    p_now, p_gender, p_mode\n) sfs ON true\n\n'
            || E'WHERE\n    (e.attrs->>''edge_type'' IS DISTINCT FROM ''same_floor_stair'' OR sfs.direction IS NOT NULL)\n    AND'
        UNION ALL
        SELECT 'public.fn_routing_edges_live(timestamptz,public.gender_enum,text,smallint)',
            'WHERE e.floor = p_floor',
            'WHERE e.floor = p_floor'
            || E'\n  AND e.attrs->>''edge_type'' IS DISTINCT FROM ''same_floor_stair'''
        UNION ALL
        SELECT 'public.fn_allowed_areas(timestamptz,public.gender_enum,text,smallint)',
            'AND NOT EXISTS (SELECT 1 FROM public.routing_connector_stops cs WHERE cs.area_id=a.id AND cs.floor=a.floor)',
            'AND NOT EXISTS (SELECT 1 FROM public.routing_connector_stops cs WHERE cs.area_id=a.id AND cs.floor=a.floor)'
            || E'\n             AND NOT (p_mode = ''walk'' AND a.id IN (SELECT public.fn_same_floor_stair_landing_areas(p_floor)))'
        ) edits
        GROUP BY signature
    LOOP
        SELECT replace(pg_get_functiondef(patch.signature::regprocedure), E'\r\n', E'\n') INTO source_sql;
        FOR edit_index IN 1..array_length(patch.old_sql, 1) LOOP
            before_text := CASE WHEN p_install THEN patch.old_sql[edit_index] ELSE patch.new_sql[edit_index] END;
            after_text := CASE WHEN p_install THEN patch.new_sql[edit_index] ELSE patch.old_sql[edit_index] END;
            IF length(source_sql) - length(replace(source_sql, before_text, '')) <> length(before_text) THEN
                RAISE EXCEPTION 'Unexpected routing definition while patching % at %', patch.signature, before_text;
            END IF;
            source_sql := replace(source_sql, before_text, after_text);
        END LOOP;
        EXECUTE source_sql;
    END LOOP;

    -- The context-free legacy view cannot enforce this link's live access policy.
    SELECT pg_get_viewdef('public.routing_edges_live'::regclass, true) INTO view_sql;
    before_text := 'COALESCE(sd.is_open_effective, true) = true';
    after_text := before_text
        || E' AND (ea.attrs ->> ''edge_type''::text) IS DISTINCT FROM ''same_floor_stair''::text';
    IF NOT p_install THEN
        SELECT after_text, before_text INTO before_text, after_text;
    END IF;
    IF length(view_sql) - length(replace(view_sql, before_text, '')) <> length(before_text) THEN
        RAISE EXCEPTION 'Unexpected routing_edges_live view definition';
    END IF;
    EXECUTE 'CREATE OR REPLACE VIEW public.routing_edges_live AS ' || replace(view_sql, before_text, after_text);
END;
